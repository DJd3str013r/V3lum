"""``v3lum scope``: draft and check ACTIVE scope files (A7 rules of engagement, A11 BR7, P378 cond 9).

* ``scope draft --from-org [-o FILE] [--force]`` writes a DRAFT scope (TOML) from the verified
  entries of the org profile (``txt_verified`` / ``attested`` domains), excluding every entry flagged
  ``third_party_hosted`` (CDN, cloud front doors, SaaS). The draft is never usable as it is: its
  ``authorization_ref`` is ``'REQUIRED'`` and owner, contacts, ticket and the UTC window are empty,
  so ``Scope.validate`` refuses it until the analyst confirms every target with the scope owner and
  binds the file to the written authorization. Networks of the profile carry no verification state:
  they are listed as comments for the analyst to confirm. Without ``-o`` the draft is printed.
* ``scope check FILE --authorized REF`` loads a scope file and lists every reason it cannot be used
  now (``Scope.validate``: malformed fields, REF mismatch, window, an ROE identity naming the
  organisation), plus an unbound draft; targets the org profile flags ``third_party_hosted`` are
  pointed out (they need the third party's own authorization).

The ACTIVE scope never defaults from the org profile: every ACTIVE run needs an explicit
``--scope FILE`` and ``--authorized REF`` (A7/A11).
"""

from __future__ import annotations

import datetime as _dt
import sys
from pathlib import Path
from typing import Any

from rich.text import Text

from v3lum import paths
from v3lum.commands import command

__all__ = ["DRAFT_REF", "ScopeCommand", "check_scope", "draft_from_org"]

#: ``authorization_ref`` of a draft: never a real reference (the analyst binds the file to one).
DRAFT_REF = "REQUIRED"


def _clean(value: Any) -> str:
    try:
        from v3lum.ui.safe import clean_text

        return clean_text(value)
    except Exception:  # noqa: BLE001 - WP14 helper unavailable: drop control characters here
        return "".join(ch for ch in str(value or "") if ch in "\n\t" or (ord(ch) >= 32 and not 0x7F <= ord(ch) <= 0x9F))


def _user_error(message: str) -> Exception:
    from v3lum.app import UserError

    return UserError(message)


def _toml_list(values: list[str]) -> str:
    from v3lum.core.orgprofile import _toml_value

    return _toml_value(list(values))


def draft_from_org(profile: Any, *, now: _dt.datetime | None = None) -> tuple[str, dict[str, int]]:
    """(TOML text of the draft scope, counts) from ``profile`` (an ``OrgProfile``).

    Targets: the verified domains (``txt_verified``/``attested``) that are not ``third_party_hosted``.
    Exclusions: every ``third_party_hosted`` domain and network of the profile (exclusions always win,
    so a wildcard the analyst adds later still leaves them out). Comments: the profile's own networks
    that are not ``third_party_hosted`` (no verification state: the analyst confirms them). Counts:
    ``domains``, ``networks`` (commented), ``excluded_third_party`` and ``unverified`` (seeded or
    confirmed domains left out).
    """
    moment = (now or _dt.datetime.now(_dt.timezone.utc)).astimezone(_dt.timezone.utc)
    domains = [d.name for d in profile.domains if d.verified and not d.third_party_hosted]
    hosted_domains = [d.name for d in profile.domains if d.third_party_hosted]
    hosted_nets = [n.value for n in profile.cidrs if n.third_party_hosted]
    unverified = sum(1 for d in profile.domains if not d.verified and not d.third_party_hosted)
    networks = [n.value for n in profile.cidrs if not n.third_party_hosted]
    lines = [
        "# V3LUM DRAFT SCOPE - generated by `v3lum scope draft --from-org` on " + moment.strftime("%Y-%m-%dT%H:%M:%SZ"),
        f"# from the verified entries of the org profile (sha256 {str(getattr(profile, 'sha256', '') or '')[:16] or '-'}).",
        "#",
        "# THIS FILE IS NOT AN AUTHORIZATION. The ACTIVE scope never defaults from the org profile (A7, A11).",
        "# Before any ACTIVE run the analyst must:",
        "#   1. confirm every target below with the scope owner and remove anything not authorised;",
        "#   2. bind the file to the written authorization: set authorization_ref to the reference passed",
        "#      with --authorized, and fill owner, contacts, ticket and the UTC window;",
        "#   3. pass it explicitly on every run: --mode active --authorized REF --scope <this file>.",
        "# Entries flagged third_party_hosted (CDN, cloud front doors, SaaS) are never targets: they are listed",
        "# under [exclusions] (exclusions always win); probing them needs the third party's own authorization.",
        "# `v3lum scope check <file> --authorized REF` validates the file.",
        f'authorization_ref = "{DRAFT_REF}"',
        'owner = ""',
        "contacts = []",
        'ticket = ""',
        'window_start = ""   # UTC, e.g. 2026-11-26T09:00:00Z',
        'window_end = ""',
        "",
        "[targets]",
        f"domains = {_toml_list(domains)}",
    ]
    if domains:
        lines.append("# add '*.<domain>' entries only when the authorization covers every subdomain")
    lines.append("cidrs = []")
    if networks:
        lines.append("# own networks of the profile (no verification state): confirm ownership before moving them into cidrs")
        lines += [f"#   {net}" for net in networks]
    lines += [
        "url_prefixes = []",
        "",
        "[exclusions]",
        "# third_party_hosted entries of the org profile",
        f"domains = {_toml_list(hosted_domains)}",
        f"cidrs = {_toml_list(hosted_nets)}",
        "url_prefixes = []",
    ]
    if unverified:
        lines += ["", f"# {unverified} unverified domain entr{'y was' if unverified == 1 else 'ies were'} left out: verify them first (v3lum org verify)"]
    counts = {"domains": len(domains), "networks": len(networks), "excluded_third_party": len(hosted_domains) + len(hosted_nets), "unverified": unverified}
    return "\n".join(lines) + "\n", counts


def check_scope(path: str, ref: str, *, org: Any = None, now: _dt.datetime | None = None) -> tuple[list[str], list[str], Any]:
    """(problems, notes, scope) of a scope file for ``--authorized ref`` now. Problems make the scope
    unusable (``Scope.validate`` plus an unbound draft); notes point out targets the org profile
    flags ``third_party_hosted``."""
    from v3lum.core.scope import Scope, ScopeError

    try:
        scope = Scope.load(path)
    except ScopeError as exc:
        return list(exc.problems), [], None
    terms: list[str] = []
    if org is not None:
        terms = [t for t in [getattr(org, "name", ""), *getattr(org, "brand_terms", lambda: [])()] if t]
    problems = list(scope.validate(ref, now, org_terms=terms))
    if scope.authorization_ref.upper() == DRAFT_REF:
        problems.insert(0, f"authorization_ref is still {DRAFT_REF!r}: this is an unbound draft (bind it to the written authorization)")
    notes: list[str] = []
    if org is not None and not getattr(org, "is_empty", True):
        for domain in sorted(scope.targets.domains | scope.targets.wildcards):
            own = org.owns(f"domain:{domain}")
            if own.own and own.third_party_hosted:
                notes.append(f"{domain}: the org profile flags it third_party_hosted - it needs the third party's own authorization")
    return problems, notes, scope


@command("scope", "ACTIVE scope files: draft one from the org profile, check one before an engagement")
class ScopeCommand:
    """Draft (never usable as is) and check ACTIVE scope files."""

    @staticmethod
    def add_arguments(parser: Any) -> None:
        sub = parser.add_subparsers(dest="scope_cmd", metavar="<action>")
        d = sub.add_parser("draft", help="write a DRAFT scope from the verified org profile entries (never usable unbound)")
        d.add_argument("--from-org", action="store_true", required=True, help="build the draft from the org profile (required)")
        d.add_argument("-o", "--out", metavar="FILE", help="write the draft here (0600); default: print it")
        d.add_argument("--force", action="store_true", help="overwrite an existing --out file")
        c = sub.add_parser("check", help="list every reason a scope file cannot be used now")
        c.add_argument("file")
        c.add_argument("--authorized", required=True, metavar="REF", help="the authorization reference the scope must be bound to")

    @staticmethod
    def run(args: Any, app: Any, console: Any) -> int:
        from v3lum.core import orgprofile

        action = getattr(args, "scope_cmd", None)
        if action is None:
            raise _user_error("usage: v3lum scope draft --from-org [-o FILE] | v3lum scope check FILE --authorized REF")
        if action == "draft":
            profile = orgprofile.load_default(app.config)
            if profile.is_empty:
                raise _user_error("no org profile: nothing to draft from (v3lum org seed / v3lum org verify)")
            text, counts = draft_from_org(profile)
            if not getattr(args, "out", None):
                sys.stdout.write(text)
            else:
                target = Path(args.out).expanduser()
                if target.exists() and not args.force:
                    raise _user_error(f"{target} exists: choose another file or pass --force")
                paths.secure_write_text(target, text)
                console.print(Text(f"[✓] draft scope written to {target} (0600)", style="v.ok"))
            summary = (
                f"{counts['domains']} verified domain(s) as targets, {counts['networks']} network(s) as comments, "
                f"{counts['excluded_third_party']} third_party_hosted entr{'y' if counts['excluded_third_party'] == 1 else 'ies'} excluded"
            )
            note = f"[!] DRAFT: {summary}. Bind it to the authorization reference before any ACTIVE run (authorization_ref = {DRAFT_REF!r})."
            if getattr(args, "out", None):
                console.print(Text(note, style="v.warn"), soft_wrap=True)
            else:  # the draft went to stdout: keep it clean for redirection
                sys.stderr.write(note + "\n")
            return 0
        if action == "check":
            try:
                org = orgprofile.load_default(app.config)
            except Exception:  # noqa: BLE001 - the org profile only adds notes
                org = None
            problems, notes, scope = check_scope(args.file, args.authorized, org=org)
            for note in notes:
                console.print(Text(f"[i] {_clean(note)}", style="v.warn"), soft_wrap=True)
            if problems:
                console.print(Text(f"[x] scope not usable ({len(problems)} problem(s)):", style="status.error"))
                for problem in problems:
                    console.print(Text(f"    - {_clean(problem)}", style="status.error"), soft_wrap=True)
                return 1
            console.print(Text(f"[✓] scope usable now for {_clean(args.authorized)}: {_clean(scope.summary())} (sha256 {scope.sha256[:16]})", style="status.ok"), soft_wrap=True)
            return 0
        raise _user_error(f"unknown scope action {action!r}")
