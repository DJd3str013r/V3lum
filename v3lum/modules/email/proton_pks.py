"""Proton Mail public key server lookup for an analyst-typed address (P092).

Endpoint adapted from ProtOSINT (https://github.com/pixelbubble/ProtOSINT, MIT licence; notice
``v3lum/data/notices/protosint_pks.json``): ``GET https://api.protonmail.ch/pks/lookup?op=index&search=<address>``
(HKP machine-readable index). V3LUM reimplements the request and parser; no ProtOSINT code is copied.

* **Typed seeds only** (cond 1): depth-0 addresses the analyst typed; pivoted, harvested, extracted,
  generated or permuted addresses (provenance from a pattern/permutation/finder service such as the Hunter
  email-finder) are refused (SKIPPED ``privacy``) - also ``run_on='seeds'`` for the policy gate.
* **Proton addresses only** (cond 2): proton.me, protonmail.com, protonmail.ch and pm.me, or a domain
  whose MX points to Proton (mail.protonmail.ch / mailsec.protonmail.ch, checked through the core DoH
  resolver); any other address gets no call (SKIPPED ``not_applicable``); an MX answer that cannot be
  verified ends ERROR (could not verify), never 'not Proton'.
* **Stored facts** (cond 3): only 'public key published' with the key fingerprint(s) and creation date(s)
  from the ``pub:<fpr>:<algo>:<bits>:<created_epoch>`` lines; UID lines are never kept. ``info:1:0`` is
  EMPTY.
* **Wording** (cond 4): 'Proton key published, created <date>' (info) with the caveat that the key date
  approximates the account creation date; a key under 30 days old in a fraud case (recorded purpose
  mentions fraud, or setting ``proton_pks_fraud_case``) is suspicious context. Absence reads 'no public
  key published', never 'no account'.
* **Never a registration oracle** (cond 5): :func:`proton_url` builds only the HKP index request on the two
  Proton key-server hosts; ProtOSINT's account.proton.me users/available method is not implemented.
* **Default set** (cond 6): the provider receives an address (PERSONAL_TYPES): the policy gate keeps it
  out of the default set until personal_data_review is recorded.
"""

from __future__ import annotations

import re
from datetime import date
from typing import Any
from urllib.parse import urlencode

from v3lum.core.entities import Entity
from v3lum.core.entities import EntityType as T
from v3lum.core.models import ModuleResult, Opsec, Status
from v3lum.core.module import Module, register
from v3lum.modules.email.pgp_keyservers import normalise_email, parse_hkp_index

SOURCE = "proton.pks"
PROTON_HOSTS = ("api.protonmail.ch", "mail-api.proton.me")
PROTON_DOMAINS = frozenset({"proton.me", "protonmail.com", "protonmail.ch", "pm.me"})
PROTON_MX_HOSTS = frozenset({"mail.protonmail.ch", "mailsec.protonmail.ch"})
NEW_KEY_DAYS = 30
ABSENT_TEXT = "no public key published"
CAVEAT = "the key creation date approximates the account creation date"
#: provenance steps that mark an address as generated, not observed (cond 1)
GENERATOR_MODULES = frozenset({"hunter_io_finder", "name_permutations", "email_permutations", "username_permutations"})
GENERATED_RELATIONS = frozenset({"guessed_email", "generated_candidate", "generated_address", "permutation_of", "candidate_address"})
_FRAUD = re.compile(r"(?i)\b(fraud|fraude|golpe|scam|estelionato|bec)\b")


def proton_url(kind: str, email: Any, host: str = PROTON_HOSTS[0]) -> str:
    """The only Proton request this module builds (cond 5): the public HKP index on a key-server host.
    ValueError for anything else (the users/available registration oracle included, rule 2)."""
    if kind != "index":
        raise ValueError("proton: only the public key-server index is allowed (users/available is a registration oracle, rule 2)")
    if host not in PROTON_HOSTS:
        raise ValueError(f"proton: host not allowed: {host!r}")
    addr = normalise_email(email)
    if addr is None:
        raise ValueError("proton: not an e-mail address")
    return f"https://{host}/pks/lookup?" + urlencode({"op": "index", "search": addr})


def generated_reason(is_seed: bool, depth: Any, provenance: Any) -> str:
    """Why an address may not be looked up (cond 1), '' when it is an analyst-typed depth-0 seed."""
    steps = [tuple(p) for p in provenance or () if isinstance(p, (list, tuple)) and len(p) >= 3]
    for _parent, relation, module in steps:
        if str(module) in GENERATOR_MODULES or str(relation) in GENERATED_RELATIONS:
            return f"address generated by {module} ({relation}): only analyst-typed addresses are looked up"
    try:
        depth_ok = int(depth or 0) == 0
    except (TypeError, ValueError):
        depth_ok = False
    if not is_seed or not depth_ok or steps:
        return "only analyst-typed seed addresses (depth 0) are looked up, never pivots or harvested addresses"
    return ""


def mx_points_to_proton(records: Any) -> bool:
    """True when an MX record names a Proton mail host ('10 mail.protonmail.ch.')."""
    for rec in records or ():
        host = str(rec).strip().split()[-1].rstrip(".").lower() if str(rec).strip() else ""
        if host in PROTON_MX_HOSTS:
            return True
    return False


def parse_proton_index(body: bytes | str) -> dict[str, Any]:
    """Proton HKP index -> stored facts only (cond 3): {is_index, declared, published, keys [{fingerprint,
    created}], earliest_created, malformed_lines}. UIDs are not returned."""
    idx = parse_hkp_index(body)
    keys = sorted(({"fingerprint": k["fingerprint"], "created": k["created"]} for k in idx["keys"] if k.get("fingerprint")),
                  key=lambda k: (k["created"] is None, k["created"] or ""))
    dated = [k["created"] for k in keys if k["created"]]
    return {"is_index": idx["is_index"], "declared": idx["declared"], "published": bool(keys), "keys": keys,
            "earliest_created": dated[0] if dated else None, "malformed_lines": idx["malformed_lines"]}


@register
class ProtonPks(Module):
    name = "proton_pks"
    title = "Proton Mail public key server"
    description = (
        "Whether Proton's public key server publishes a key for an analyst-typed Proton address (Proton domains or "
        "domains with Proton MX), with the key fingerprint and creation date (approximates account creation)."
    )
    category = "email"
    accepts = {T.EMAIL}
    produces = frozenset()
    run_on = "seeds"
    reference = "https://github.com/pixelbubble/ProtOSINT"
    notice = (
        "Public key-discovery directory, never a registration or reset flow: analyst-typed Proton addresses only (no "
        "guessed or harvested addresses). Absence means 'no public key published', never 'no account'. Endpoint adapted "
        "from ProtOSINT (MIT)."
    )
    terms = "open"
    opsec = Opsec.PASSIVE
    disclosure = "third_party"
    provider = "proton"
    sources = (SOURCE,)
    hosts = (PROTON_HOSTS[0],)
    access_model = "free_noauth_limited"
    max_requests = 1  # the MX check goes through the core DoH resolver (not counted)
    expected_latency = 0.7
    timeout = 30.0
    min_interval = 2.0
    cache_ttl = 86400
    max_pivots = 0
    default_enabled = True  # effective default only after personal_data_review (policy gate, cond 6)
    settings = {"proton_pks_fraud_case": False}
    error_markers = (
        {"id": "proton_api_error", "statuses": [200, 400, 422], "json_path": "Error", "regex": "\\S", "maps_to": "error",
         "reason_code": "error", "reason": "Proton API error object instead of a key-server index: could not verify"},
    )

    def applies(self, entity: Entity, ctx: Any) -> bool:
        return normalise_email(entity.value) is not None

    def run(self, entity: Entity, ctx: Any) -> ModuleResult:
        res = self.result(entity)
        refused = generated_reason(bool(getattr(ctx, "is_seed", False)), getattr(ctx, "depth", 0), getattr(ctx, "provenance", ()))
        if refused:
            return res.mark(Status.SKIPPED, refused, reason_code="privacy")
        addr = normalise_email(entity.value) or ""
        domain = addr.rsplit("@", 1)[1]
        via = "proton_domain"
        if domain not in PROTON_DOMAINS:
            answer = ctx.dns.query(domain, "MX")
            if answer.could_not_verify:
                return res.mark(Status.ERROR, f"MX of {domain} could not be verified ({answer.error or answer.status}): Proton key server not queried")
            if not (answer.ok and mx_points_to_proton(answer.records)):
                return res.mark(Status.SKIPPED, "not a Proton domain and its MX does not point to Proton: no key-server call",
                                reason_code="not_applicable")
            via = "proton_mx"
        resp = ctx.http.get(proton_url("index", addr), source=SOURCE, headers={"Accept": "text/plain"})
        ctx.http.check(resp)  # 403/429/5xx/challenges/API error objects: could not verify
        if "html" in str(resp.headers.get("content-type", "")).lower():
            return res.mark(Status.ERROR, "Proton served HTML instead of a key-server index: could not verify")
        parsed = parse_proton_index(resp.content)
        if not parsed["is_index"] or (not parsed["published"] and parsed["malformed_lines"]):
            return res.mark(Status.ERROR, "unexpected Proton key-server answer: could not verify")
        if not parsed["published"]:
            res.raw = {"published": False, "via": via}
            res.attr("proton_key", {"published": False})
            res.error = ABSENT_TEXT
            return res.mark(Status.EMPTY)
        age = None
        if parsed["earliest_created"]:
            try:
                age = (ctx.now().date() - date.fromisoformat(parsed["earliest_created"][:10])).days
            except ValueError:
                age = None
        fact = {"published": True, "keys": parsed["keys"], "earliest_created": parsed["earliest_created"], "age_days": age}
        res.raw = dict(fact, via=via)
        res.attr("proton_key", fact)
        created = parsed["earliest_created"][:10] if parsed["earliest_created"] else "unknown date"
        res.finding(
            "Proton key published",
            "info",
            f"Proton key published, created {created} ({CAVEAT}). {len(parsed['keys'])} key(s) listed by the Proton key server.",
            confidence="probable",
            criterion="Proton public key server (HKP index) lists a key for the address",
            data={"created": parsed["earliest_created"], "keys": len(parsed["keys"]), "via": via},
            source=SOURCE,
            observed_first=parsed["earliest_created"],
        )
        if age is not None and 0 <= age < NEW_KEY_DAYS and self._fraud_case(ctx):
            res.finding(
                "Recently created Proton key (fraud case context)",
                "low",
                f"The Proton key is {age} day(s) old: in a fraud case a freshly created mailbox is suspicious context "
                f"({CAVEAT}). Context only, never proof.",
                confidence="possible",
                criterion=f"key created less than {NEW_KEY_DAYS} days ago in a case whose purpose is fraud",
                data={"age_days": age, "created": parsed["earliest_created"]},
                tags=["context_only"],
                source=SOURCE,
            )
        return res

    @staticmethod
    def _fraud_case(ctx: Any) -> bool:
        if ctx.setting("proton_pks_fraud_case", False) is True:
            return True
        return bool(_FRAUD.search(str(getattr(ctx, "purpose", "") or "")))
