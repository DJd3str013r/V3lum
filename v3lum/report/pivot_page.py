"""Standalone manual-pivot page of a case (P311 cond 10-11, P336, A2).

One self-contained HTML page per case with every manual pivot link, under the same
Content-Security-Policy as the report (``report.html.csp``: no external resource of any kind, the
bundled script allowed by its hash only) and the no-referrer meta:

* grouped by entity (seeds first) and by analyst question (reputation, history, passive DNS,
  code/paste, social, ...), manual fallbacks ('automation skipped: <reason>') and verified links
  first, unverified ones with their badge ('unverified', 'unknown operator');
* TLP rules (A2, P311 cond 5): clickable only at TLP:CLEAR/GREEN; at AMBER and above every link is
  defanged text with 'opening sends <value> to <host>'; at RED third-party links are omitted (only
  ``v3lum links`` shows them, with the warning);
* touches_target links (they open the target or make a third party fetch it live) are defanged and
  never clickable; for hostile entities they sit in a collapsed block the analyst must expand
  (P311 cond 8); personal-data links only with ``show_personal`` (P311 cond 6);
* the TLP marking in the header, at the top of every section, in the footer and in print CSS.

V3LUM never fetches these links itself: the page only lists them (P311 cond 11).
"""

from __future__ import annotations

from typing import Any

from v3lum.report import summary as S
from v3lum.report.html import _TLP_CLASSES, CSS, JS, _flag, _Page, _print_css, csp, e, pivot_body, tlp_badge
from v3lum.ui.safe import clean_text

__all__ = ["render"]


def render(case: dict[str, Any], *, show_personal: bool | None = None, no_defang: bool | None = None) -> str:
    """The manual-pivot page of a case (self-contained HTML, same CSP as the report). The view flags
    default to the ones recorded in ``case['options']``; links follow ``summary.pivot_plan``."""
    case = case if isinstance(case, dict) else {}
    show_personal = _flag(show_personal, case, "show_personal")
    no_defang = _flag(no_defang, case, "no_defang")
    case = S.shareable_view(case)
    p = _Page(case, show_personal=show_personal, no_defang=no_defang)
    plan = S.pivot_plan(case, show_personal=show_personal, no_defang=no_defang, full=True)
    label = S.tlp_label(case)
    cid = clean_text(case.get("case_id") or "?")
    head = (
        f'<header><div>{tlp_badge(case)} <span class="tlpdesc">{e(S.tlp_description(case))}</span></div>'
        f'<div class="logo">V3LUM</div><div class="tag">manual pivots :: case {e(cid)}</div>'
        '<div class="warn">V3LUM never fetches these links. Opening one sends the value to its host and shows that host '
        "your IP address: use your OPSEC setup.</div>"
    )
    for line in S.engagement_block(case, show_personal=show_personal, no_defang=no_defang):
        head += f'<div class="warn">{e(line)}</div>'
    head += "</header>"
    toolbar = '<div class="toolbar"><input id="q" placeholder="filter links..."></div>'
    if plan.entities or plan.hidden_red or plan.hidden_privacy or plan.dropped:
        body = p.section("pivots", "Manual pivots", toolbar + pivot_body(p, plan, filterable=True), plan.count)
    else:
        body = p.section("pivots", "Manual pivots", '<p class="muted">No manual pivot links for this case.</p>', 0)
    return "".join(
        [
            '<!doctype html><html lang="en"><head><meta charset="utf-8">',
            f'<meta http-equiv="Content-Security-Policy" content="{e(csp())}">',
            '<meta name="referrer" content="no-referrer">',
            '<meta name="robots" content="noindex,nofollow">',
            '<meta name="viewport" content="width=device-width,initial-scale=1">',
            f"<title>V3LUM manual pivots {e(cid)} - {e(label)}</title>",
            f"<style>{CSS}{_print_css(case)}</style></head><body>",
            f'<div class="tlp-print tlp tlp-{_TLP_CLASSES.get(S.tlp_value(case), "red")}" aria-hidden="true">{e(label)}</div>',
            '<div class="wrap">',
            head,
            body,
            f'<footer>{p.mark}<p>Generated by V3LUM. Links are suggestions for manual lookups; V3LUM never fetches them.</p>'
            f"<div>{tlp_badge(case)}</div></footer>",
            f"</div><script>{JS}</script></body></html>",
        ]
    )
